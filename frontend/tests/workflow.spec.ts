import { test, expect } from '@playwright/test';

test('empty start, connected replay, approval, timeout reconciliation and persistence', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByText('A shared view.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Run analysis', exact: true })).toHaveCount(0);
  await page.screenshot({ path: 'test-results/empty-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Explore demo', exact: true }).click();
  await page.getByRole('button', { name: 'Load demo dataset', exact: true }).click();
  await expect(page.getByLabel('Product rules', { exact: true })).toHaveValue('');
  await page.getByLabel('Product rules', { exact: true }).selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Run analysis', exact: true }).click();
  await expect(page.getByText('Your latest analysis is ready to explore.')).toBeVisible();
  await page.screenshot({ path: 'test-results/overview-desktop.png', fullPage: true });
  const firstPortfolio = await page.getByLabel('Portfolio', { exact: true }).inputValue();
  await page.getByLabel('Portfolio', { exact: true }).selectOption({ index: 2 });
  await expect(page.getByText('Your portfolio is ready. Let’s look ahead.')).toBeVisible();
  await page.getByLabel('Portfolio', { exact: true }).selectOption(firstPortfolio);
  await expect(page.getByText('Your latest analysis is ready to explore.')).toBeVisible();
  await page.getByRole('link', { name: 'Storm workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Next bulletin', exact: true }).click();
  await expect(page.getByText(/A newer input is selected/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Create payout draft', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Next bulletin', exact: true }).click();
  await page.getByRole('button', { name: 'Next bulletin', exact: true }).click();
  await page.getByRole('button', { name: 'Run analysis', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Create payout draft', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Create payout draft', exact: true }).click();
  await page.getByRole('link', { name: /Actions & payouts/ }).click();
  await page.getByRole('button', { name: 'Submit for approval', exact: true }).click();
  await expect(page.getByText('0 open', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Approve batch', exact: true })).toBeDisabled();
  await page.getByLabel('Demo role').selectOption('Approver');
  await page.getByRole('button', { name: 'Approve batch', exact: true }).click();
  await page.getByLabel('Payment outcome').selectOption('timeout');
  await page.getByRole('button', { name: 'Simulate payment', exact: true }).click();
  await expect(page.getByText('Awaiting reconciliation', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Reconcile unknown', exact: true }).click();
  await expect(page.getByText('All simulated payments reconciled')).toBeVisible();
  await page.reload();
  await expect(page.getByText('All simulated payments reconciled')).toBeVisible();
  await page.screenshot({ path: 'test-results/payouts-desktop.png', fullPage: true });
  await page.getByRole('link', { name: 'Pricing lab', exact: true }).click();
  await expect(page.getByLabel('Coverage days')).toHaveValue('');
  await page.getByLabel('Coverage days').fill('90');
  await page.getByRole('button', { name: 'Calculate scenario', exact: true }).click();
  await expect(page.getByText('90-day scenario', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/overview-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});

test('invalid import stays empty and valid import becomes a linked portfolio', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Import portfolio', exact: true }).click();
  await expect(page.getByLabel('Portfolio JSON')).toHaveValue('');
  await page.getByLabel('Portfolio JSON').fill('{"name":"Bad","merchants":[]}');
  await page.getByRole('button', { name: 'Validate records' }).click();
  await expect(page.getByRole('button', { name: 'Confirm import' })).toBeDisabled();
  const data = { name: 'Independent import', merchants: [{ id: 'custom-1', name: 'Custom shop', region: 'Cebu', lat: 10.31, lng: 123.89, sumInsured: 2000000, coverageStart: '2026-01-01T00:00:00.000Z', coverageEnd: '2026-12-31T23:59:59.000Z' }] };
  await page.getByLabel('Portfolio JSON').fill(JSON.stringify(data));
  await page.getByRole('button', { name: 'Validate records' }).click();
  await page.getByRole('button', { name: 'Confirm import' }).click();
  await expect(page.getByRole('button', { name: 'Custom shop', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Storm workspace', exact: true }).click();
  await expect(page.getByLabel('Storm', { exact: true })).toHaveValue('');
  await page.getByLabel('Storm', { exact: true }).selectOption({ index: 1 });
  await page.getByLabel('Product rules', { exact: true }).selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Run analysis', exact: true }).click();
  await expect(page.getByText('Analysis snapshot', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Analysis snapshot', { exact: true })).toBeVisible();
});

test('partial and failed model responses block settlement, then confirmed payment failures can retry', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore demo', exact: true }).click();
  await page.getByRole('button', { name: 'Load demo dataset', exact: true }).click();
  await page.getByLabel('Product rules', { exact: true }).selectOption({ index: 1 });
  await page.getByRole('link', { name: 'Storm workspace', exact: true }).click();
  for (let i = 0; i < 3; i++) await page.getByRole('button', { name: 'Next bulletin', exact: true }).click();
  await page.getByRole('button', { name: 'Simulation controls' }).click();
  await page.getByLabel('Model response').selectOption('partial');
  await page.getByRole('button', { name: 'Run analysis', exact: true }).click();
  await expect(page.getByText(/Partial result: some locations/)).toBeVisible();
  await expect(page.getByRole('button', { name: 'Create payout draft', exact: true })).toBeDisabled();
  await page.getByLabel('Model response').selectOption('failure');
  await page.getByRole('button', { name: 'Run analysis', exact: true }).click();
  await expect(page.getByText('Analysis could not finish.')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Create payout draft', exact: true })).toBeDisabled();
  await page.getByLabel('Model response').selectOption('none');
  await page.getByRole('button', { name: 'Run analysis', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Create payout draft', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Create payout draft', exact: true }).click();
  await page.getByRole('link', { name: /Actions & payouts/ }).click();
  await page.getByRole('button', { name: 'Submit for approval', exact: true }).click();
  await page.getByLabel('Demo role').selectOption('Approver');
  await page.getByRole('button', { name: 'Approve batch', exact: true }).click();
  await page.getByLabel('Payment outcome').selectOption('failure');
  await page.getByRole('button', { name: 'Simulate payment', exact: true }).click();
  await expect(page.getByText('failed', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Retry failed items', exact: true }).click();
  await expect(page.getByText('All simulated payments reconciled')).toBeVisible();
});
