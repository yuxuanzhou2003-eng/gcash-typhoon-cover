import { test, expect } from '@playwright/test';

// Opt-in: uses the server's configured paid model, never a browser API key.
test('live agent pipeline, evidence, human decisions and persisted history', async ({ page }) => {
  test.skip(process.env.RUN_LIVE_AGENT_TEST !== '1', 'Requires an explicitly enabled live provider.');
  test.setTimeout(240_000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore demo', exact: true }).click();
  await page.getByRole('button', { name: 'Load demo dataset', exact: true }).click();
  await page.getByLabel('Product rules', { exact: true }).selectOption({ index: 1 });
  await page.getByRole('button', { name: 'Run analysis', exact: true }).click();
  await expect(page.getByText('Your latest analysis is ready to explore.')).toBeVisible();
  await page.getByRole('link', { name: 'Agent workspace', exact: true }).click();
  await expect(page.getByText('Live AI', { exact: true })).toBeVisible();
  const start = page.getByRole('button', { name: 'Run agents', exact: true });
  if (await start.count()) await start.click();
  else await page.getByRole('button', { name: 'Run again', exact: true }).click();
  await expect(page.locator('.agent-run-status')).toHaveText('Completed', { timeout: 180_000 });
  await expect(page.locator('.agent-step-completed')).toHaveCount(3);
  await expect(page.getByText('Review ready', { exact: true })).toBeVisible();
  await page.getByText('View stage details', { exact: true }).first().click();
  await page.locator('.agent-evidence summary').first().click();
  await expect(page.locator('.agent-fact').first()).toBeVisible();
  await page.screenshot({ path: 'test-results/agents-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Accept & open task', exact: true }).first().click();
  await expect(page).toHaveURL(/#payouts$/);
  await expect(page.getByRole('heading', { name: 'Your accepted tasks', exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Your accepted tasks', exact: true })).toBeVisible();
  const accepted = page.locator('.task-flow-card-accepted:not(.is-stale)').first();
  await expect(accepted.getByRole('button', { name: 'Mark complete', exact: true })).toBeDisabled();
  await accepted.getByRole('checkbox').check();
  await accepted.getByRole('button', { name: 'Mark complete', exact: true }).click();
  await expect(page.getByText('Completion recorded by a human', { exact: true }).first()).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'test-results/agents-mobile.png', fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 1050 });
  await page.getByRole('link', { name: 'Storm workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Next bulletin', exact: true }).click();
  await page.getByRole('link', { name: 'Agent workspace', exact: true }).click();
  for (const button of await page.getByRole('button', { name: 'Accept & open task', exact: true }).all()) await expect(button).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Run agents', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: /Actions & payouts/ }).click();
  await expect(page.getByRole('heading', { name: 'Your accepted tasks', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
